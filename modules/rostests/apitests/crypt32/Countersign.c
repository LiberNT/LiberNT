static
HCRYPTPROV
ImportKey(LPCWSTR Container, const BYTE *Blob, DWORD Size)
{
    HCRYPTPROV Prov = 0;
    HCRYPTKEY Key;

    CryptAcquireContextW(&Prov, Container, MS_ENH_RSA_AES_PROV_W, PROV_RSA_AES, CRYPT_DELETEKEYSET);
    if (!CryptAcquireContextW(&Prov, Container, MS_ENH_RSA_AES_PROV_W, PROV_RSA_AES, CRYPT_NEWKEYSET))
        return 0;
    if (!CryptImportKey(Prov, Blob, Size, 0, 0, &Key))
    {
        CryptReleaseContext(Prov, 0);
        return 0;
    }
    CryptDestroyKey(Key);
    return Prov;
}

static
VOID
Cleanup(VOID)
{
    HCRYPTPROV Prov;

    if (SignerProv)
        CryptReleaseContext(SignerProv, 0);
    if (TsaProv)
        CryptReleaseContext(TsaProv, 0);
    if (WeakProv)
        CryptReleaseContext(WeakProv, 0);
    CryptAcquireContextW(&Prov, SIGNER_CONTAINER, MS_ENH_RSA_AES_PROV_W, PROV_RSA_AES, CRYPT_DELETEKEYSET);
    CryptAcquireContextW(&Prov, TSA_CONTAINER, MS_ENH_RSA_AES_PROV_W, PROV_RSA_AES, CRYPT_DELETEKEYSET);
    CryptAcquireContextW(&Prov, WEAK_CONTAINER, MS_ENH_RSA_AES_PROV_W, PROV_RSA_AES, CRYPT_DELETEKEYSET);
    if (Signer)
        CertFreeCertificateContext(Signer);
    if (Tsa)
        CertFreeCertificateContext(Tsa);
    if (Root)
        CertFreeCertificateContext(Root);
    if (Weak)
        CertFreeCertificateContext(Weak);
}

static
VOID
InitSigner(CMSG_SIGNER_ENCODE_INFO *Info, PCCERT_CONTEXT Cert, HCRYPTPROV Prov, LPCSTR HashOid)
{
    ZeroMemory(Info, sizeof(*Info));
    Info->cbSize = sizeof(*Info);
    Info->pCertInfo = Cert->pCertInfo;
    Info->hCryptProv = Prov;
    Info->dwKeySpec = AT_SIGNATURE;
    Info->HashAlgorithm.pszObjId = (LPSTR)HashOid;
}

static
BYTE *
GetParam(HCRYPTMSG Msg, DWORD Type, DWORD Index, DWORD *Size)
{
    BYTE *Buffer;

    *Size = 0;
    if (!CryptMsgGetParam(Msg, Type, Index, NULL, Size) || !(Buffer = HeapAlloc(GetProcessHeap(), 0, *Size)))
        return NULL;
    if (CryptMsgGetParam(Msg, Type, Index, Buffer, Size))
        return Buffer;
    HeapFree(GetProcessHeap(), 0, Buffer);
    return NULL;
}

static
BOOL
HashIs(const BYTE *Data, DWORD Size, const BYTE *Expected, DWORD ExpectedSize)
{
    BYTE Hash[32];
    DWORD HashSize = sizeof(Hash);

    return CryptHashCertificate(0, CALG_SHA_256, 0, Data, Size, Hash, &HashSize) && HashSize >= ExpectedSize &&
           !memcmp(Hash, Expected, ExpectedSize);
}

static
BYTE *
SignContent(DWORD *Size)
{
    CMSG_SIGNER_ENCODE_INFO SignerInfo;
    CMSG_SIGNED_ENCODE_INFO SignedInfo;
    CERT_BLOB Certs[3];
    HCRYPTMSG Msg;
    BYTE *Encoded = NULL;

    InitSigner(&SignerInfo, Signer, SignerProv, szOID_NIST_sha256);
    Certs[0].cbData = Signer->cbCertEncoded;
    Certs[0].pbData = Signer->pbCertEncoded;
    Certs[1].cbData = Root->cbCertEncoded;
    Certs[1].pbData = Root->pbCertEncoded;
    Certs[2].cbData = Tsa->cbCertEncoded;
    Certs[2].pbData = Tsa->pbCertEncoded;
    ZeroMemory(&SignedInfo, sizeof(SignedInfo));
    SignedInfo.cbSize = sizeof(SignedInfo);
    SignedInfo.cSigners = 1;
    SignedInfo.rgSigners = &SignerInfo;
    SignedInfo.cCertEncoded = RTL_NUMBER_OF(Certs);
    SignedInfo.rgCertEncoded = Certs;
    Msg = CryptMsgOpenToEncode(ENCODING, 0, CMSG_SIGNED, &SignedInfo, NULL, NULL);
    if (!Msg)
        return NULL;
    if (CryptMsgUpdate(Msg, Content, sizeof(Content), TRUE))
        Encoded = GetParam(Msg, CMSG_CONTENT_PARAM, 0, Size);
    CryptMsgClose(Msg);
    return Encoded;
}

static
HCRYPTMSG
Decode(const BYTE *Data, DWORD Size)
{
    HCRYPTMSG Msg = CryptMsgOpenToDecode(ENCODING, 0, 0, 0, NULL, NULL);

    if (Msg && !CryptMsgUpdate(Msg, Data, Size, TRUE))
    {
        CryptMsgClose(Msg);
        return NULL;
    }
    return Msg;
}

static
VOID
CheckEncoded(BYTE *SignerInfo, DWORD SignerInfoSize, CMSG_SIGNER_ENCODE_INFO *Countersigner, DWORD ExpectedSize,
             const BYTE *ExpectedHash, ULONG Line)
{
    BYTE *Buffer;
    DWORD Size = 0;
    BOOL Ret;

    Ret = CryptMsgCountersignEncoded(ENCODING, SignerInfo, SignerInfoSize, 1, Countersigner, NULL, &Size);
    ok_(__FILE__, Line)(Ret, "CryptMsgCountersignEncoded failed with 0x%lx\n", GetLastError());
    ok_(__FILE__, Line)(Size == ExpectedSize, "size %lu, expected %lu\n", Size, ExpectedSize);
    if (!Ret || !(Buffer = HeapAlloc(GetProcessHeap(), 0, Size)))
        return;
    Ret = CryptMsgCountersignEncoded(ENCODING, SignerInfo, SignerInfoSize, 1, Countersigner, Buffer, &Size);
    ok_(__FILE__, Line)(Ret && Size == ExpectedSize && HashIs(Buffer, Size, ExpectedHash, 32),
                        "unexpected countersignature (%d, %lu)\n", Ret, Size);
    HeapFree(GetProcessHeap(), 0, Buffer);
}

static
BOOL
GetCountersignature(BYTE *SignerInfo, DWORD SignerInfoSize, CMSG_SIGNER_ENCODE_INFO *Countersigner,
                    CRYPT_DATA_BLOB *Countersignature)
{
    CRYPT_ATTRIBUTE *Attribute;
    BYTE *Buffer;
    DWORD Size = 0;

    Countersignature->cbData = 0;
    Countersignature->pbData = NULL;
    if (!CryptMsgCountersignEncoded(ENCODING, SignerInfo, SignerInfoSize, 1, Countersigner, NULL, &Size) ||
        !(Buffer = HeapAlloc(GetProcessHeap(), 0, Size)))
        return FALSE;
    if (CryptMsgCountersignEncoded(ENCODING, SignerInfo, SignerInfoSize, 1, Countersigner, Buffer, &Size) &&
        CryptDecodeObjectEx(ENCODING, PKCS_ATTRIBUTE, Buffer, Size, CRYPT_DECODE_ALLOC_FLAG, NULL, &Attribute, &Size))
    {
        ok(!strcmp(Attribute->pszObjId, szOID_RSA_counterSign), "attribute %s\n", Attribute->pszObjId);
        ok_long(Attribute->cValue, 1);
        Countersignature->cbData = Attribute->rgValue[0].cbData;
        Countersignature->pbData = HeapAlloc(GetProcessHeap(), 0, Countersignature->cbData);
        if (Countersignature->pbData)
            memcpy(Countersignature->pbData, Attribute->rgValue[0].pbData, Countersignature->cbData);
        LocalFree(Attribute);
    }
    HeapFree(GetProcessHeap(), 0, Buffer);
    return Countersignature->pbData != NULL;
}

