static
VOID
CheckPolicy(LPCSTR Policy, PCCERT_CHAIN_CONTEXT Chain, DWORD Flags, DWORD Error, LONG Element, ULONG Line)
{
    CERT_CHAIN_POLICY_PARA Para = { sizeof(Para), Flags };
    CERT_CHAIN_POLICY_STATUS Status = { sizeof(Status) };

    ok_(__FILE__, Line)(CertVerifyCertificateChainPolicy(Policy, Chain, &Para, &Status), "policy failed\n");
    ok_(__FILE__, Line)(Status.dwError == Error, "error 0x%lx, expected 0x%lx\n", Status.dwError, Error);
    ok_(__FILE__, Line)(Status.lChainIndex == (Element < 0 ? -1 : 0) && Status.lElementIndex == Element,
                        "chain %ld element %ld, expected %ld\n", Status.lChainIndex, Status.lElementIndex, Element);
}

static
PCCERT_CHAIN_CONTEXT
BuildChain(PCCERT_CONTEXT Leaf, HCERTSTORE Store, DWORD Flags)
{
    CERT_CHAIN_PARA Para = { sizeof(Para) };
    PCCERT_CHAIN_CONTEXT Chain = NULL;

    ok(CertGetCertificateChain(NULL, Leaf, NULL, Store, &Para, Flags, NULL, &Chain), "CertGetCertificateChain failed 0x%lx\n",
       GetLastError());
    return Chain;
}

START_TEST(ChainRevocation)
{
    static const struct
    {
        DWORD Flags;
        DWORD Element[3];
    } Builds[] =
    {
        { 0, { 0, 0, 0 } },
        { CERT_CHAIN_REVOCATION_CHECK_END_CERT, { CERT_TRUST_REVOCATION_STATUS_UNKNOWN, 0, 0 } },
        { CERT_CHAIN_REVOCATION_CHECK_CHAIN, { CERT_TRUST_REVOCATION_STATUS_UNKNOWN, CERT_TRUST_REVOCATION_STATUS_UNKNOWN, 0 } },
        { CERT_CHAIN_REVOCATION_CHECK_CHAIN_EXCLUDE_ROOT,
          { CERT_TRUST_REVOCATION_STATUS_UNKNOWN, CERT_TRUST_REVOCATION_STATUS_UNKNOWN, 0 } },
    };
    PCCERT_CONTEXT Root, Inter, Leaf, Added = NULL;
    PCCERT_CHAIN_CONTEXT Chain;
    HCERTSTORE Store, MachineRoot;
    DWORD i, j;

    Root = CertCreateCertificateContext(X509_ASN_ENCODING, RootCert, sizeof(RootCert));
    Inter = CertCreateCertificateContext(X509_ASN_ENCODING, InterCert, sizeof(InterCert));
    Leaf = CertCreateCertificateContext(X509_ASN_ENCODING, LeafCert, sizeof(LeafCert));
    Store = CertOpenStore(CERT_STORE_PROV_MEMORY, 0, 0, 0, NULL);
    MachineRoot = CertOpenStore(CERT_STORE_PROV_SYSTEM_W, 0, 0, CERT_SYSTEM_STORE_LOCAL_MACHINE, L"Root");
    if (!Root || !Inter || !Leaf || !Store || !MachineRoot ||
        !CertAddCertificateContextToStore(MachineRoot, Root, CERT_STORE_ADD_REPLACE_EXISTING, &Added))
    {
        skip("Cannot set up the chain (0x%lx)\n", GetLastError());
        return;
    }
    CertAddCertificateContextToStore(Store, Inter, CERT_STORE_ADD_ALWAYS, NULL);

    for (i = 0; i < RTL_NUMBER_OF(Builds); i++)
    {
        winetest_push_context("flags 0x%lx", Builds[i].Flags);
        Chain = BuildChain(Leaf, Store, Builds[i].Flags);
        if (Chain)
        {
            ok_long(Chain->cChain, 1);
            ok_long(Chain->rgpChain[0]->cElement, 3);
            for (j = 0; j < 3 && j < Chain->rgpChain[0]->cElement; j++)
                ok(Chain->rgpChain[0]->rgpElement[j]->TrustStatus.dwErrorStatus == Builds[i].Element[j],
                   "element %lu error 0x%lx, expected 0x%lx\n", j,
                   Chain->rgpChain[0]->rgpElement[j]->TrustStatus.dwErrorStatus, Builds[i].Element[j]);
            CertFreeCertificateChain(Chain);
        }
        winetest_pop_context();
    }

    Chain = BuildChain(Leaf, Store, CERT_CHAIN_REVOCATION_CHECK_CHAIN_EXCLUDE_ROOT);
    if (Chain)
    {
        CheckPolicy(CERT_CHAIN_POLICY_BASE, Chain, 0, CRYPT_E_NO_REVOCATION_CHECK, 0, __LINE__);
        CheckPolicy(CERT_CHAIN_POLICY_BASE, Chain, CERT_CHAIN_POLICY_IGNORE_END_REV_UNKNOWN_FLAG,
                    CRYPT_E_NO_REVOCATION_CHECK, 1, __LINE__);
        CheckPolicy(CERT_CHAIN_POLICY_BASE, Chain, CERT_CHAIN_POLICY_IGNORE_ALL_REV_UNKNOWN_FLAGS, NO_ERROR, -1, __LINE__);
        CheckPolicy(CERT_CHAIN_POLICY_AUTHENTICODE, Chain, 0, CERT_E_REVOCATION_FAILURE, 0, __LINE__);
        CheckPolicy(CERT_CHAIN_POLICY_AUTHENTICODE, Chain, CERT_CHAIN_POLICY_IGNORE_END_REV_UNKNOWN_FLAG, NO_ERROR, -1,
                    __LINE__);
        CheckPolicy(CERT_CHAIN_POLICY_AUTHENTICODE, Chain, CERT_CHAIN_POLICY_IGNORE_ALL_REV_UNKNOWN_FLAGS, NO_ERROR, -1,
                    __LINE__);
        CertFreeCertificateChain(Chain);
    }
    Chain = BuildChain(Leaf, Store, 0);
    if (Chain)
    {
        CheckPolicy(CERT_CHAIN_POLICY_BASE, Chain, 0, NO_ERROR, -1, __LINE__);
        CheckPolicy(CERT_CHAIN_POLICY_AUTHENTICODE, Chain, 0, NO_ERROR, -1, __LINE__);
        CertFreeCertificateChain(Chain);
    }

    CertDeleteCertificateFromStore(Added);
    CertCloseStore(MachineRoot, 0);
    CertCloseStore(Store, 0);
    CertFreeCertificateContext(Leaf);
    CertFreeCertificateContext(Inter);
    CertFreeCertificateContext(Root);
}
