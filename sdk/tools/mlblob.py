import argparse
import struct
import sys

USAGE = '''
ML64 cannot assemble 16-bit or 32-bit code. Mixed-mode trampolines are written
once in GAS syntax and assembled by the GCC/Clang build; this tool turns the
resulting COFF object range [START, END) into a MASM include of DB lines with
every label of the range at its original offset, for the _USE_ML path.

Regenerate after changing the GAS source, from a GCC/Clang build object:
  python sdk/tools/mlblob.py OBJECT START END --source FILE.S -o FILE.inc [--base SYMBOL]

--base adds an ML64 assembly-time check that START sits at the same offset
from SYMBOL as in the GAS object, for ranges that follow ML64-written code.

Verify an ML64 object against the GAS object:
  python sdk/tools/mlblob.py OBJECT START END --compare ML64OBJECT
'''


def read_coff(path):
    data = open(path, 'rb').read()
    machine, nsect, _, symptr, nsym, opthdr, _ = struct.unpack_from('<HHIIIHH', data, 0)
    if machine != 0x8664:
        raise SystemExit('%s: not an AMD64 COFF object (machine 0x%04x)' % (path, machine))
    strtab = symptr + nsym * 18
    sections = []
    for index in range(nsect):
        base = 20 + opthdr + index * 40
        raw = struct.unpack_from('<8sIIIIIIHHI', data, base)
        sections.append({'size': raw[3], 'rawptr': raw[4], 'relptr': raw[5], 'nreloc': raw[7]})
    symbols = []
    index = 0
    while index < nsym:
        base = symptr + index * 18
        name, value, secnum, _, sclass, naux = struct.unpack_from('<8sIhHBB', data, base)
        if name[:4] == b'\0\0\0\0':
            offset = struct.unpack_from('<I', name, 4)[0]
            end = data.index(b'\0', strtab + offset)
            name = data[strtab + offset:end]
        else:
            name = name.rstrip(b'\0')
        if sclass in (2, 3) and secnum > 0 and naux == 0 and not name.startswith(b'.'):
            symbols.append((name.decode('ascii'), secnum, value))
        index += 1 + naux
    return data, sections, symbols


def find_range(path, start, end):
    data, sections, symbols = read_coff(path)
    table = {}
    for name, secnum, value in symbols:
        table.setdefault(name, (secnum, value))
    for name in (start, end):
        if name not in table:
            raise SystemExit('%s: symbol %s not found' % (path, name))
    secnum, first = table[start]
    if table[end][0] != secnum or table[end][1] < first:
        raise SystemExit('%s: %s does not follow %s in the same section' % (path, end, start))
    last = table[end][1]
    section = sections[secnum - 1]
    if section['rawptr'] == 0 or last > section['size']:
        raise SystemExit('%s: range has no raw data' % path)
    for index in range(section['nreloc']):
        offset = struct.unpack_from('<I', data, section['relptr'] + index * 10)[0]
        if first <= offset < last:
            raise SystemExit('%s: relocation at 0x%x inside the range' % (path, offset))
    blob = data[section['rawptr'] + first:section['rawptr'] + last]
    labels = sorted((value - first, name) for name, num, value in symbols
                    if num == secnum and first <= value < last)
    labels.append((last - first, end))
    return blob, labels, table, secnum


def header_from(source, start, end):
    lines = open(source, encoding='utf-8').read().splitlines()
    keep = []
    copyright_block = False
    for line in lines[1:]:
        if line.startswith(' */'):
            break
        if line.startswith(' * PROJECT:') or line.startswith(' * LICENSE:'):
            keep.append(line)
            copyright_block = False
        elif line.startswith(' * COPYRIGHT:'):
            keep.append(line)
            copyright_block = True
        elif copyright_block and line.startswith(' *  ') and line.strip(' *'):
            keep.append(line)
        else:
            copyright_block = False
    purpose = ' * PURPOSE:     MASM image of %s..%s generated by sdk/tools/mlblob.py' % (start, end)
    return ['/*'] + keep[:2] + [purpose] + keep[2:] + [' */', '']


def emit(args):
    blob, labels, table, secnum = find_range(args.object, args.start, args.end)
    out = header_from(args.source, args.start, args.end) if args.source else []
    position = 0
    for index, (offset, name) in enumerate(labels):
        out.append('%s:' % name)
        stop = labels[index + 1][0] if index + 1 < len(labels) else offset
        position = offset
        while position < stop:
            chunk = blob[position:min(stop, position + 12)]
            out.append('    DB ' + ', '.join('0%02Xh' % byte for byte in chunk))
            position += len(chunk)
    if args.base:
        if args.base not in table or table[args.base][0] != secnum:
            raise SystemExit('%s: base symbol %s not in the range section' % (args.object, args.base))
        delta = table[args.start][1] - table[args.base][1]
        out.append('.ERRNZ (%s - %s) - 0%Xh' % (args.start, args.base, delta))
    text = '\r\n'.join(out) + '\r\n'
    with open(args.output, 'w', newline='') as handle:
        handle.write(text)


def compare(args):
    gas_blob, gas_labels, _, _ = find_range(args.object, args.start, args.end)
    ml_blob, ml_labels, _, _ = find_range(args.compare, args.start, args.end)
    status = 0
    if len(gas_blob) != len(ml_blob):
        status = 1
        print('size mismatch: gas 0x%x ml 0x%x' % (len(gas_blob), len(ml_blob)))
    for offset in range(min(len(gas_blob), len(ml_blob))):
        if gas_blob[offset] != ml_blob[offset]:
            status = 1
            print('byte mismatch at +0x%x: gas %02x ml %02x' % (offset, gas_blob[offset], ml_blob[offset]))
    gas_names = {n: o for o, n in gas_labels}
    ml_names = {n: o for o, n in ml_labels}
    for name in sorted(ml_names):
        if gas_names.get(name) != ml_names[name]:
            status = 1
            print('label %s at +0x%x in ML64 object differs from GAS object' % (name, ml_names[name]))
    for name in sorted(set(gas_names) - set(ml_names)):
        print('label %s at +0x%x not in ML64 symbol table, not checked' % (name, gas_names[name]))
    if status == 0:
        print('identical: %d bytes, %d labels' % (len(gas_blob), len(ml_names)))
    return status


def main():
    parser = argparse.ArgumentParser(description=USAGE, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('object')
    parser.add_argument('start')
    parser.add_argument('end')
    parser.add_argument('-o', '--output')
    parser.add_argument('--source')
    parser.add_argument('--base')
    parser.add_argument('--compare')
    args = parser.parse_args()
    if args.compare:
        return compare(args)
    if not args.output:
        parser.error('-o is required')
    emit(args)
    return 0


if __name__ == '__main__':
    sys.exit(main())
