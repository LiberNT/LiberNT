CERTIFICATE_HEADER = """; "{cert_name}" ({cert_size} bytes)
HKLM,"SOFTWARE\\Microsoft\\SystemCertificates\\{store}\\Certificates\\{fingerprint_sha1}","Blob",0x00000001,\\
{properties}    0x20,0x00,0x00,0x00,\\
    0x01,0x00,0x00,0x00,\\
    {cert_size_hex},\\
{data}
"""


@dataclass
class Certificate:
    name: str
    fingerprint_sha1: str
    data: bytes
    properties: list[tuple[int, bytes]] = field(default_factory=list)
    store: str = "AuthRoot"


def hex_lines(data: bytes, last: bool) -> list[str]:
    hex_bytes = [f"0x{b:02X}" for b in data]
    lines = []
    for i in range(0, len(hex_bytes), 16):
        line = ",".join(hex_bytes[i : i + 16])
        if not last or i + 16 < len(hex_bytes):
            line += ",\\"
        lines.append("    " + line)
    return lines


def format_property(prop_id: int, value: bytes) -> str:
    header = struct.pack("<III", prop_id, 1, len(value))
    return "\n".join(hex_lines(header, False) + hex_lines(value, False)) + "\n"


def format_certificate(cert: Certificate) -> str:
    # Format the data as comma-separated hex bytes, 16 bytes per line
    hex_bytes = [f"0x{b:02X}" for b in cert.data]
    lines = []
    for i in range(0, len(hex_bytes), 16):
        line = ",".join(hex_bytes[i : i + 16])
        if i + 16 < len(hex_bytes):
            line += ",\\"
        lines.append("    " + line)

    cert_size = len(cert.data)
    cert_size_hex = ",".join(f"0x{b:02X}" for b in cert_size.to_bytes(4, byteorder="little"))

    return CERTIFICATE_HEADER.format(
        cert_name=cert.name,
        fingerprint_sha1=cert.fingerprint_sha1,
        store=cert.store,
        properties="".join(format_property(prop_id, value) for prop_id, value in cert.properties),
        cert_size=cert_size,
        cert_size_hex=cert_size_hex,
        data="\n".join(lines),
    )


class CurrentBlock(Enum):
    Begin = 0
    Certificate = 1
    Trust = 2


def parse_certificates2(certdata: str) -> list[Certificate]:
    cert = None
    result = []
    temp_value = None
    block = CurrentBlock.Begin

    for line in certdata.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue

        if line == "CKA_CLASS CK_OBJECT_CLASS CKO_NSS_TRUST":
            block = CurrentBlock.Trust
            continue
        elif line == "CKA_CLASS CK_OBJECT_CLASS CKO_CERTIFICATE":
            block = CurrentBlock.Certificate
            continue
        elif line.startswith("CKA_LABEL"):
            _, name, _ = line.split('"')
            if block == CurrentBlock.Certificate:
                cert = Certificate(name=name, fingerprint_sha1="", data=b"")
            elif block == CurrentBlock.Trust:
                assert cert is not None, line
                assert name == cert.name
            else:
                pass
        elif line == "CKA_VALUE MULTILINE_OCTAL":
            assert cert is not None
            temp_value = []
            assert cert.data == b""
            assert cert.fingerprint_sha1 == ""
        elif line == "CKA_CERT_SHA1_HASH MULTILINE_OCTAL":
            assert cert is not None
            temp_value = []
            assert cert.data != b""
            assert cert.fingerprint_sha1 == ""
        elif temp_value is not None:
            assert cert is not None
            if line == "END":
                if cert.data == b"":
                    cert.data = bytes(temp_value)
                else:
                    assert cert.fingerprint_sha1 == ""
                    cert.fingerprint_sha1 = "".join(f"{b:02X}" for b in temp_value)
                temp_value = None
            else:
                for number in line.split("\\"):
                    if not number:
                        continue
                    temp_value.append(int(number, 8))

        elif line.startswith("CKA_TRUST_SERVER_AUTH"):
            assert cert is not None
            if "CKT_NSS_TRUSTED_DELEGATOR" in line:
                print(f"Trusted cert: {cert.name} ({len(cert.data)} bytes)")
                result.append(cert)
            cert = None
    return result


def read_der(data: bytes, offset: int) -> tuple[int, int, int]:
    tag = data[offset]
    length = data[offset + 1]
    offset += 2
    if length & 0x80:
        count = length & 0x7F
        length = int.from_bytes(data[offset : offset + count], "big")
        offset += count
    return tag, offset, offset + length


def read_der_children(data: bytes, start: int, end: int) -> list[tuple[int, int, int]]:
    result = []
    while start < end:
        tag, content, content_end = read_der(data, start)
        result.append((tag, content, content_end))
        start = content_end
    return result


def certificate_name(der: bytes) -> str:
    encodings = {0x0C: "utf-8", 0x13: "ascii", 0x14: "latin-1", 0x16: "ascii", 0x1E: "utf-16-be"}
    names = {}
    _, start, end = read_der(der, 0)
    _, start, end = read_der(der, start)
    fields = read_der_children(der, start, end)
    if fields[0][0] == 0xA0:
        fields = fields[1:]
    _, start, end = fields[4]
    for _, set_start, set_end in read_der_children(der, start, end):
        for _, seq_start, seq_end in read_der_children(der, set_start, set_end):
            oid, value = read_der_children(der, seq_start, seq_end)[:2]
            text = der[value[1] : value[2]].decode(encodings.get(value[0], "latin-1"), "replace")
            names[der[oid[1] : oid[2]]] = text
    for oid in (b"\x55\x04\x03", b"\x55\x04\x0B", b"\x55\x04\x0A"):
        if oid in names:
            return names[oid]
    return "Unnamed"


def extract_cab_file(cab: bytes) -> bytes:
    """Return the first file of a single-folder MSZIP cabinet."""
    if cab[:4] != b"MSCF":
        raise ValueError("not a cabinet")
    flags = struct.unpack_from("<H", cab, 30)[0]
    offset = 36
    folder_reserve = data_reserve = 0
    if flags & 4:
        header_reserve, folder_reserve, data_reserve = struct.unpack_from("<HBB", cab, offset)
        offset += 4 + header_reserve
    data_offset, block_count, compression = struct.unpack_from("<IHH", cab, offset)
    if compression & 0xF != 1:
        raise ValueError("cabinet is not MSZIP compressed")
    output = b""
    offset = data_offset
    for _ in range(block_count):
        compressed, _ = struct.unpack_from("<HH", cab, offset + 4)
        block = cab[offset + 8 + data_reserve : offset + 8 + data_reserve + compressed]
        if block[:2] != b"CK":
            raise ValueError("bad MSZIP block")
        inflater = zlib.decompressobj(-15, zdict=output[-32768:]) if output else zlib.decompressobj(-15)
        output += inflater.decompress(block[2:]) + inflater.flush()
        offset += 8 + data_reserve + compressed
    return output


def decode_oid(data: bytes) -> str:
    values = [data[0] // 40, data[0] % 40]
    value = 0
    for byte in data[1:]:
        value = (value << 7) | (byte & 0x7F)
        if not byte & 0x80:
            values.append(value)
            value = 0
    return ".".join(map(str, values))


def parse_authroot_properties(stl: bytes) -> dict[str, dict[int, bytes]]:
    """Map each root of a Microsoft authroot.stl CTL to its root program properties."""
    _, start, end = read_der(stl, 0)
    content_info = read_der_children(stl, start, end)
    _, start, end = read_der(stl, content_info[1][1])
    signed_data = read_der_children(stl, start, end)
    encapsulated = read_der_children(stl, signed_data[2][1], signed_data[2][2])
    tag, start, end = read_der(stl, encapsulated[1][1])
    if tag == 0x04:
        tag, start, end = read_der(stl, start)
    result = {}
    for tag, list_start, list_end in read_der_children(stl, start, end):
        if tag != 0x30:
            continue
        for subject_tag, subject_start, subject_end in read_der_children(stl, list_start, list_end):
            parts = read_der_children(stl, subject_start, subject_end) if subject_tag == 0x30 else []
            if not parts or parts[0][0] != 0x04 or parts[0][2] - parts[0][1] != 20:
                break
            properties = {}
            for _, attr_start, attr_end in (read_der_children(stl, parts[1][1], parts[1][2]) if len(parts) > 1 else []):
                oid, values = read_der_children(stl, attr_start, attr_end)[:2]
                name = decode_oid(stl[oid[1] : oid[2]])
                if name.startswith(AUTHROOT_PROPERTY_OID):
                    value = read_der_children(stl, values[1], values[2])[0]
                    properties[int(name[len(AUTHROOT_PROPERTY_OID):])] = stl[value[1] : value[2]]
            result[stl[parts[0][1] : parts[0][2]].hex().upper()] = properties
    return result


def download(url: str) -> bytes:
    with urllib.request.urlopen(url) as response:
        return response.read()


def notbefore_codesign_roots(report_url: str, authroot_url: str, cert_url: str) -> list[Certificate]:
    """Code signing roots Microsoft keeps trusted up to a NotBefore cut-off, with that cut-off."""
    report = csv.DictReader(io.StringIO(download(report_url).decode("utf-8-sig")))
    fingerprints = [row["SHA-1 Fingerprint"].upper() for row in report
                    if row["Microsoft Status"] == "NotBefore" and "Code Signing" in row["Microsoft EKUs"]]
    properties = parse_authroot_properties(extract_cab_file(download(authroot_url)))
    result = []
    for fingerprint in fingerprints:
        root = properties.get(fingerprint, {})
        if CERT_NOT_BEFORE_FILETIME_PROP_ID not in root:
            print(f"Skipping NotBefore root {fingerprint}: authroot.stl has no NotBefore time")
            continue
        data = download(cert_url.format(fingerprint=fingerprint))
        if hashlib.sha1(data).hexdigest().upper() != fingerprint:
            raise ValueError(f"downloaded root {fingerprint} does not match its fingerprint")
        cert = Certificate(name=certificate_name(data), fingerprint_sha1=fingerprint, data=data)
        for prop_id in (CERT_NOT_BEFORE_FILETIME_PROP_ID, CERT_NOT_BEFORE_ENHKEY_USAGE_PROP_ID):
            if prop_id in root:
                cert.properties.append((prop_id, root[prop_id]))
        print(f"NotBefore code signing cert: {cert.name} ({len(cert.data)} bytes)")
        result.append(cert)
    return result


def certificate_serial(der: bytes) -> str:
    _, start, end = read_der(der, 0)
    _, start, end = read_der(der, start)
    fields = read_der_children(der, start, end)
    if fields[0][0] == 0xA0:
        fields = fields[1:]
    return der[fields[0][1] : fields[0][2]].hex().upper()


def required_windows_roots(cert_url: str) -> list[Certificate]:
    """Roots Windows ships built in, checked against the fingerprint and the serial Microsoft lists."""
    result = []
    for fingerprint, serial in REQUIRED_ROOTS:
        data = download(cert_url.format(fingerprint=fingerprint))
        if hashlib.sha1(data).hexdigest().upper() != fingerprint:
            raise ValueError(f"downloaded root {fingerprint} does not match its fingerprint")
        if certificate_serial(data).lstrip("0") != serial.lstrip("0"):
            raise ValueError(f"root {fingerprint} does not have serial {serial}")
        cert = Certificate(name=certificate_name(data), fingerprint_sha1=fingerprint, data=data, store="ROOT")
        print(f"Required Windows root: {cert.name} ({len(cert.data)} bytes)")
        result.append(cert)
    return result


def parse_pem_bundle(bundle: str) -> list[Certificate]:
    result = []
    for body in re.findall(
        r"-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----", bundle, re.S
    ):
        data = base64.b64decode(body)
        cert = Certificate(
            name=certificate_name(data),
            fingerprint_sha1=hashlib.sha1(data).hexdigest().upper(),
            data=data,
        )
        print(f"Code signing cert: {cert.name} ({len(cert.data)} bytes)")
        result.append(cert)
    return result


def main():
    parser = argparse.ArgumentParser(
        description="Update the caroots.inf file with the latest CA root certificates."
    )
    parser.add_argument(
        "--url",
        type=str,
        default=DEFAULT_DOWNLOAD_URL,
        help="URL to download the certdata.txt file from.",
    )
    parser.add_argument(
        "--codesign-url",
        type=str,
        default=DEFAULT_CODESIGN_URL,
        help="URL to download the PEM bundle of code signing roots from.",
    )
    parser.add_argument(
        "--msft-report-url",
        type=str,
        default=DEFAULT_MSFT_REPORT_URL,
        help="URL of the Microsoft root program report listing each root's status.",
    )
    parser.add_argument(
        "--authroot-url",
        type=str,
        default=DEFAULT_AUTHROOT_URL,
        help="URL of the Microsoft authroot.stl cabinet holding the roots' properties.",
    )
    parser.add_argument(
        "--root-cert-url",
        type=str,
        default=DEFAULT_ROOT_CERT_URL,
        help="URL pattern of a Microsoft root certificate by SHA-1 fingerprint.",
    )
    args = parser.parse_args()

    print(f"Downloading certdata.txt from {args.url}...")
    with urllib.request.urlopen(args.url) as response:
        certdata = response.read().decode("utf-8")

    print("Parsing certdata.txt...")
    certificates = parse_certificates2(certdata)

    print(f"Downloading code signing roots from {args.codesign_url}...")
    with urllib.request.urlopen(args.codesign_url) as response:
        bundle = response.read().decode("utf-8")

    known = {cert.fingerprint_sha1 for cert in certificates}
    for cert in parse_pem_bundle(bundle):
        if cert.fingerprint_sha1 not in known:
            known.add(cert.fingerprint_sha1)
            certificates.append(cert)

    print("Downloading the roots Windows requires...")
    for cert in required_windows_roots(args.root_cert_url):
        if cert.fingerprint_sha1 not in known:
            known.add(cert.fingerprint_sha1)
            certificates.append(cert)

    print(f"Downloading NotBefore code signing roots from {args.msft_report_url}...")
    for cert in notbefore_codesign_roots(args.msft_report_url, args.authroot_url, args.root_cert_url):
        if cert.fingerprint_sha1 not in known:
            known.add(cert.fingerprint_sha1)
            certificates.append(cert)
    certificates.sort(key=lambda c: c.name.lower())
    print(f"Found {len(certificates)} trusted root certificates.")
    print(f"Updating {CAROOTS_INF}...")
    with CAROOTS_INF.open("w", encoding="utf-8", newline="\r\n") as f:
        f.write(
            CAROOTS_HEADER.format(
                source_url=args.url,
                codesign_url=args.codesign_url,
                notbefore_url=args.msft_report_url,
                authroot_url=args.authroot_url,
                required_url=REQUIRED_ROOTS_SOURCE,
                date=datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
                cert_count=len(certificates),
            )
        )
        for cert in certificates:
            f.write(format_certificate(cert))
            f.write("\n")

    print("Update complete.")


if __name__ == "__main__":
    main()
