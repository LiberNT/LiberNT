#!/usr/bin/env python3
"""
PROJECT:     LiberNT build tools
LICENSE:     GPL-3.0-or-later (https://spdx.org/licenses/GPL-3.0-or-later)
PURPOSE:     Write cursor files as raw cursor and cursor group resources
COPYRIGHT:   Copyright 2026 Ahmed ARIF <arif.ing@outlook.com>

rc.exe checks every image of a CURSOR statement and refuses PNG images, which
LoadImage accepts. This tool reads NAME CURSOR "FILE" lines, writes each image
of each file as an RT_CURSOR resource (hotspot followed by the image) and each
name as an RT_GROUP_CURSOR directory, and writes the resource script that
includes them. Names that use the same file share its images.

rc.exe also reserves the resource types below 256 for its own statements, so
it cannot take those resources from files either. Given an output .res and a
header defining the symbolic names, the tool writes them to that compiled
resource file for the linker instead, and the resource script stays empty.

    curres.py <list> <source dir> <output .rc> [<output .res> <names header>]
"""

import os
import re
import struct
import sys

RT_CURSOR = 1
RT_GROUP_CURSOR = 12
RES_CURSOR_FLAGS = 0x1010
RES_GROUP_CURSOR_FLAGS = 0x1030
PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"
PNG_CHANNELS = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}
LINE = re.compile(r'^\s*(\S+)\s+CURSOR\s+"([^"]+)"\s*$')


def image_format(path, index, image):
    if image[:8] == PNG_SIGNATURE:
        if len(image) < 26 or image[12:16] != b"IHDR":
            sys.exit("%s: image %d has no PNG header" % (path, index))
        depth, color = image[24], image[25]
        if color not in PNG_CHANNELS:
            sys.exit("%s: image %d has PNG color type %d" % (path, index, color))
        return 1, depth * PNG_CHANNELS[color]
    if len(image) < 16:
        sys.exit("%s: image %d is too small for a bitmap header" % (path, index))
    return struct.unpack_from("<HH", image, 12)


def read_cursor(path):
    data = open(path, "rb").read()
    if len(data) < 6:
        sys.exit("%s: too small for a cursor directory" % path)
    reserved, kind, count = struct.unpack_from("<HHH", data, 0)
    if reserved != 0 or kind != 2 or count == 0 or len(data) < 6 + 16 * count:
        sys.exit("%s: not a cursor file" % path)
    images = []
    for index in range(count):
        width, height, _, _, x, y, size, offset = struct.unpack_from("<BBBBHHII", data, 6 + 16 * index)
        image = data[offset:offset + size]
        if len(image) != size:
            sys.exit("%s: image %d runs past the end of the file" % (path, index))
        planes, bits = image_format(path, index, image)
        images.append((width or 256, height or 256, planes, bits, x, y, image))
    return images


def read_list(path):
    entries = []
    for number, text in enumerate(open(path), 1):
        text = re.sub(r"/\*.*?\*/", "", text).strip()
        if not text:
            continue
        match = LINE.match(text)
        if not match:
            sys.exit("%s:%d: expected NAME CURSOR \"FILE\"" % (path, number))
        entries.append((match.group(1), match.group(2)))
    return entries


def read_names(path):
    names = {}
    for text in open(path, errors="replace"):
        match = re.match(r"^\s*#\s*define\s+(\w+)\s+(\d+)\s*$", text)
        if match:
            names[match.group(1)] = int(match.group(2))
    return names


def name_id(name, names):
    if name.isdigit():
        return int(name)
    if name not in names:
        sys.exit("%s: no numeric value for this resource name" % name)
    return names[name]


def res_entry(kind, ident, data, flags):
    header = struct.pack("<IIHHHHIHHII", len(data), 32, 0xFFFF, kind, 0xFFFF, ident, 0, flags, 0, 0, 0)
    return header + data + b"\0" * (-len(data) % 4)


def main():
    if len(sys.argv) not in (4, 6):
        sys.exit("usage: curres.py <list> <source dir> <output .rc> [<output .res> <names header>]")
    entries = read_list(sys.argv[1])
    source, output = sys.argv[2], sys.argv[3]
    res_output = sys.argv[4] if len(sys.argv) == 6 else None
    names = read_names(sys.argv[5]) if res_output else {}
    res = [struct.pack("<IIHHHHIHHII", 0, 32, 0xFFFF, 0, 0xFFFF, 0, 0, 0, 0, 0, 0)]
    folder = os.path.splitext(output)[0]
    os.makedirs(folder, exist_ok=True)

    groups = {}
    lines = ["/* Generated by curres.py from %s */" % os.path.basename(sys.argv[1])]
    next_id = 1
    for name, file in entries:
        if file not in groups:
            stem = os.path.splitext(os.path.basename(file))[0]
            directory = struct.pack("<HHH", 0, 2, 0)
            count = 0
            for index, (width, height, planes, bits, x, y, image) in enumerate(read_cursor(os.path.join(source, file))):
                resource = struct.pack("<HH", x, y) + image
                target = os.path.join(folder, "%s.%d.bin" % (stem, index))
                open(target, "wb").write(resource)
                lines.append('%d %d "%s"' % (next_id, RT_CURSOR, target.replace("\\", "/")))
                res.append(res_entry(RT_CURSOR, next_id, resource, RES_CURSOR_FLAGS))
                directory += struct.pack("<HHHHIH", width, height * 2, planes, bits, len(resource), next_id)
                next_id += 1
                count += 1
            directory = struct.pack("<HHH", 0, 2, count) + directory[6:]
            target = os.path.join(folder, stem + ".grp")
            open(target, "wb").write(directory)
            groups[file] = target.replace("\\", "/")
        lines.append('%s %d "%s"' % (name, RT_GROUP_CURSOR, groups[file]))
        if res_output:
            res.append(res_entry(RT_GROUP_CURSOR, name_id(name, names), open(groups[file], "rb").read(),
                                 RES_GROUP_CURSOR_FLAGS))

    if res_output:
        open(res_output, "wb").write(b"".join(res))
        lines = lines[:1]
    open(output, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
