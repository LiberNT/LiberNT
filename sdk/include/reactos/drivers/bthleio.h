#pragma once

#define IOCTL_BTHLE_GATT_GET_DESCRIPTORS \
    CTL_CODE(FILE_DEVICE_BLUETOOTH, 0xc2, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_BTHLE_GATT_GET_INCLUDED_SERVICES \
    CTL_CODE(FILE_DEVICE_BLUETOOTH, 0xc3, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_BTHLE_GATT_READ_VALUE \
    CTL_CODE(FILE_DEVICE_BLUETOOTH, 0xd1, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_BTHLE_GATT_WRITE_VALUE \
    CTL_CODE(FILE_DEVICE_BLUETOOTH, 0xd2, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_BTHLE_GATT_EXECUTE_WRITE \
    CTL_CODE(FILE_DEVICE_BLUETOOTH, 0xd3, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_BTHLE_GATT_WAIT_NOTIFICATION \
    CTL_CODE(FILE_DEVICE_BLUETOOTH, 0xd4, METHOD_BUFFERED, FILE_ANY_ACCESS)

#define BTHLE_GATT_READ_FROM_DEVICE         0x00000001
#define BTHLE_GATT_READ_FROM_CACHE          0x00000002
#define BTHLE_GATT_WRITE_WITHOUT_RESPONSE   0x00000001
#define BTHLE_GATT_WRITE_SIGNED             0x00000002
#define BTHLE_GATT_WRITE_PREPARE            0x00000004

typedef struct _BTHLE_GATT_DESCRIPTORS
{
    USHORT CharacteristicHandle;
    ULONG Count;
    BTH_LE_GATT_DESCRIPTOR Descriptors[ANYSIZE_ARRAY];
} BTHLE_GATT_DESCRIPTORS, *PBTHLE_GATT_DESCRIPTORS;

typedef struct _BTHLE_GATT_INCLUDED_SERVICES
{
    USHORT ServiceHandle;
    ULONG Count;
    BTH_LE_GATT_SERVICE Services[ANYSIZE_ARRAY];
} BTHLE_GATT_INCLUDED_SERVICES, *PBTHLE_GATT_INCLUDED_SERVICES;

typedef struct _BTHLE_GATT_VALUE
{
    USHORT Handle;
    UCHAR AttError;
    ULONG Flags;
    ULONG Size;
    UCHAR Data[ANYSIZE_ARRAY];
} BTHLE_GATT_VALUE, *PBTHLE_GATT_VALUE;

typedef struct _BTHLE_GATT_EXECUTE_WRITE
{
    BOOLEAN Commit;
    UCHAR AttError;
} BTHLE_GATT_EXECUTE_WRITE, *PBTHLE_GATT_EXECUTE_WRITE;

typedef struct _BTHLE_GATT_NOTIFICATION
{
    ULONG Sequence;
    USHORT Handle;
    BOOLEAN Lost;
    ULONG Size;
    UCHAR Data[BTH_LE_ATT_MAX_VALUE_SIZE];
} BTHLE_GATT_NOTIFICATION, *PBTHLE_GATT_NOTIFICATION;
