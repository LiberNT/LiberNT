#pragma once

#define LNT_WINUSB_VERSION 1
#define LNT_WINUSB_MAX_INTERFACES 16
#define LNT_WINUSB_MAX_CONTROL_LENGTH 4096
#define LNT_WINUSB_MAXIMUM_TRANSFER_SIZE (2 * 1024 * 1024)
#define LNT_WINUSB_DEFAULT_CONTROL_TIMEOUT 5000

#define LNT_WINUSB_IOCTL(Function, Method) CTL_CODE(FILE_DEVICE_UNKNOWN, 0xB40 + (Function), Method, FILE_ANY_ACCESS)

#define IOCTL_LNT_WINUSB_INITIALIZE       LNT_WINUSB_IOCTL(0, METHOD_BUFFERED)
#define IOCTL_LNT_WINUSB_GET_DESCRIPTOR   LNT_WINUSB_IOCTL(1, METHOD_OUT_DIRECT)
#define IOCTL_LNT_WINUSB_SET_SETTING      LNT_WINUSB_IOCTL(2, METHOD_BUFFERED)
#define IOCTL_LNT_WINUSB_GET_SETTING      LNT_WINUSB_IOCTL(3, METHOD_BUFFERED)
#define IOCTL_LNT_WINUSB_SET_PIPE_POLICY  LNT_WINUSB_IOCTL(4, METHOD_BUFFERED)
#define IOCTL_LNT_WINUSB_GET_PIPE_POLICY  LNT_WINUSB_IOCTL(5, METHOD_BUFFERED)
#define IOCTL_LNT_WINUSB_SET_POWER_POLICY LNT_WINUSB_IOCTL(6, METHOD_BUFFERED)
#define IOCTL_LNT_WINUSB_GET_POWER_POLICY LNT_WINUSB_IOCTL(7, METHOD_BUFFERED)
#define IOCTL_LNT_WINUSB_READ_PIPE        LNT_WINUSB_IOCTL(8, METHOD_OUT_DIRECT)
#define IOCTL_LNT_WINUSB_WRITE_PIPE       LNT_WINUSB_IOCTL(9, METHOD_IN_DIRECT)
#define IOCTL_LNT_WINUSB_CONTROL_IN       LNT_WINUSB_IOCTL(10, METHOD_OUT_DIRECT)
#define IOCTL_LNT_WINUSB_CONTROL_OUT      LNT_WINUSB_IOCTL(11, METHOD_IN_DIRECT)
#define IOCTL_LNT_WINUSB_RESET_PIPE       LNT_WINUSB_IOCTL(12, METHOD_BUFFERED)
#define IOCTL_LNT_WINUSB_ABORT_PIPE       LNT_WINUSB_IOCTL(13, METHOD_BUFFERED)
#define IOCTL_LNT_WINUSB_FLUSH_PIPE       LNT_WINUSB_IOCTL(14, METHOD_BUFFERED)
#define IOCTL_LNT_WINUSB_GET_FRAME_NUMBER LNT_WINUSB_IOCTL(15, METHOD_BUFFERED)

typedef struct _LNT_WINUSB_INFORMATION
{
    ULONG Version;
    ULONG Size;
    UCHAR Speed;
    UCHAR InterfaceCount;
    UCHAR InterfaceNumbers[LNT_WINUSB_MAX_INTERFACES];
    UCHAR DeviceDescriptor[18];
    USHORT ConfigurationLength;
    UCHAR Configuration[ANYSIZE_ARRAY];
} LNT_WINUSB_INFORMATION, *PLNT_WINUSB_INFORMATION;

typedef struct _LNT_WINUSB_PIPE_REQUEST
{
    UCHAR InterfaceIndex;
    UCHAR PipeId;
    USHORT Reserved;
} LNT_WINUSB_PIPE_REQUEST, *PLNT_WINUSB_PIPE_REQUEST;

typedef struct _LNT_WINUSB_SETTING_REQUEST
{
    UCHAR InterfaceIndex;
    UCHAR AlternateSetting;
    USHORT Reserved;
} LNT_WINUSB_SETTING_REQUEST, *PLNT_WINUSB_SETTING_REQUEST;

typedef struct _LNT_WINUSB_POLICY_REQUEST
{
    UCHAR InterfaceIndex;
    UCHAR PipeId;
    USHORT Reserved;
    ULONG PolicyType;
    ULONG ValueLength;
    ULONG Value;
} LNT_WINUSB_POLICY_REQUEST, *PLNT_WINUSB_POLICY_REQUEST;

typedef struct _LNT_WINUSB_CONTROL_REQUEST
{
    UCHAR InterfaceIndex;
    UCHAR Reserved[7];
    UCHAR SetupPacket[8];
} LNT_WINUSB_CONTROL_REQUEST, *PLNT_WINUSB_CONTROL_REQUEST;

typedef struct _LNT_WINUSB_DESCRIPTOR_REQUEST
{
    UCHAR InterfaceIndex;
    UCHAR DescriptorType;
    UCHAR Index;
    UCHAR Reserved;
    USHORT LanguageId;
    USHORT Reserved2;
} LNT_WINUSB_DESCRIPTOR_REQUEST, *PLNT_WINUSB_DESCRIPTOR_REQUEST;

typedef struct _LNT_WINUSB_FRAME_NUMBER
{
    ULONG FrameNumber;
    ULONG Reserved;
    LARGE_INTEGER TimeStamp;
} LNT_WINUSB_FRAME_NUMBER, *PLNT_WINUSB_FRAME_NUMBER;
