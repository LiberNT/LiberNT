#pragma once

#define APPLE_AGX_DEVICE_NAME L"\\Device\\AppleAgx"

/* Asked by the display driver before it sends anything to the graphics processor. */
#define IOCTL_APPLE_AGX_QUERY_STATE CTL_CODE(FILE_DEVICE_VIDEO, 0x920, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_APPLE_AGX_GET_PARAMS  CTL_CODE(FILE_DEVICE_VIDEO, 0x921, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_APPLE_AGX_VM_CREATE   CTL_CODE(FILE_DEVICE_VIDEO, 0x922, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_APPLE_AGX_VM_DESTROY  CTL_CODE(FILE_DEVICE_VIDEO, 0x923, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_APPLE_AGX_GEM_CREATE  CTL_CODE(FILE_DEVICE_VIDEO, 0x924, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_APPLE_AGX_GEM_CLOSE   CTL_CODE(FILE_DEVICE_VIDEO, 0x925, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_APPLE_AGX_GEM_MAP     CTL_CODE(FILE_DEVICE_VIDEO, 0x926, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_APPLE_AGX_VM_BIND     CTL_CODE(FILE_DEVICE_VIDEO, 0x927, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_APPLE_AGX_QUEUE_CREATE CTL_CODE(FILE_DEVICE_VIDEO, 0x928, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_APPLE_AGX_QUEUE_DESTROY CTL_CODE(FILE_DEVICE_VIDEO, 0x929, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_APPLE_AGX_SUBMIT      CTL_CODE(FILE_DEVICE_VIDEO, 0x92a, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_APPLE_AGX_GEM_BIND_OBJECT CTL_CODE(FILE_DEVICE_VIDEO, 0x92b, METHOD_BUFFERED, FILE_ANY_ACCESS)

#define APPLE_AGX_DOS_DEVICE_NAME L"\\DosDevices\\AppleAgx"

typedef struct _APPLE_AGX_GEM_HANDLE
{
    ULONG Handle;
    ULONG Flags;
    ULONG64 Address;
} APPLE_AGX_GEM_HANDLE, *PAPPLE_AGX_GEM_HANDLE;

/* How far the graphics processor has come. Rendering is offered only when it is ready. */
#define APPLE_AGX_STATE_ABSENT      0
#define APPLE_AGX_STATE_IDENTIFIED  1
#define APPLE_AGX_STATE_ADOPTED     2
#define APPLE_AGX_STATE_STARTED     3
#define APPLE_AGX_STATE_READY       4

typedef struct _APPLE_AGX_REPORT
{
    ULONG State;
    ULONG Generation;
    ULONG Variant;
    ULONG Revision;
    ULONG Clusters;
    ULONG CoresPerCluster;
    ULONG ActiveCores;
    ULONG TopKilohertz;
    ULONG64 Records;
} APPLE_AGX_REPORT, *PAPPLE_AGX_REPORT;
