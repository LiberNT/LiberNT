    ULONG RxTail;
    volatile LONG RxReturnedSinceKick;

    PRTL8168_DESC TxRing;
    NDIS_PHYSICAL_ADDRESS TxRingPhysical;
    ULONG TxRingLength;
    RTL8168_TX_BUFFER TxBuffers[RTL8168_TX_RING_SIZE];
    ULONG TxHead;
    ULONG TxTail;
    ULONG TxFree;

