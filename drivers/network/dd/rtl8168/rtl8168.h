    ULONG HwRev;
    ULONG64 LinkSpeed;
    NDIS_MEDIA_CONNECT_STATE MediaConnectState;
    NDIS_MEDIA_DUPLEX_STATE MediaDuplexState;
    NDIS_HANDLE LinkTimer;
    BOOLEAN DatapathReady;
