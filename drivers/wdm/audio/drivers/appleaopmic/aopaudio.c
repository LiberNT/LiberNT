typedef struct _AOP_AUDIO_ATTACH
{
    ULONG Zero0;
    ULONG Unknown0;
    ULONG CallType;
    ULONG64 Zero1;
    ULONG64 Zero2;
    ULONG Pad0;
    ULONG64 Length;
    ULONG DeviceId;
    ULONG Pad1;
} AOP_AUDIO_ATTACH;

typedef struct _AOP_AUDIO_SET_PROPERTY
{
    ULONG Zero0;
    ULONG Unknown0;
    ULONG CallType;
    UCHAR Zero1[8];
    UCHAR Zero2[8];
    ULONG Pad0;
    ULONG Length;
    ULONG Pad1;
    ULONG DeviceId;
    ULONG Modifier;
    ULONG Length2;
} AOP_AUDIO_SET_PROPERTY;

typedef struct _AOP_LPAI_CHANNELS
{
    ULONG Enabled;
    ULONG Supported;
    ULONG VoiceTriggerChannel;
    ULONG Unknown4;
} AOP_LPAI_CHANNELS;

typedef struct _AOP_DECIMATOR
{
    ULONG Latency;
    UCHAR Ratio1;
    UCHAR Ratio2;
    UCHAR Ratio3;
    UCHAR Pad0;
    ULONG FilterLengths;
    ULONG CoefficientCount;
    UCHAR Coefficients[DECIM_NUM_COEFFS * sizeof(ULONG)];
} AOP_DECIMATOR;

typedef struct _AOP_PDM_CONFIG
{
    ULONG BytesPerSample;
    ULONG ClockSource;
    ULONG PdmFrequency;
    ULONG PdmcFrequency;
    ULONG SlowClockSpeed;
    ULONG FastClockSpeed;
    ULONG ChannelPolaritySelect;
    UCHAR Unknown1;
    ULONG ChannelPhaseSelect;
    UCHAR Unknown2;
    AOP_DECIMATOR Decimator;
    ULONG MicTurnOnTimeValid;
    ULONG MicTurnOnTimeMs;
    UCHAR Zero0[8];
    UCHAR Zero1[8];
    ULONG MicSettleTimeValid;
    ULONG MicSettleTimeMs;
    UCHAR Zero2[69];
    UCHAR PadExtra;
} AOP_PDM_CONFIG;

typedef struct _AOP_DECIMATOR_HF
{
    ULONG Latency;
    UCHAR Ratio1;
    UCHAR Ratio2;
    UCHAR Ratio3;
    UCHAR Pad0;
    ULONG FilterLengths;
    ULONG CoefficientCount;
    UCHAR Coefficients[DECIM_NUM_COEFFS_HF * sizeof(ULONG64)];
} AOP_DECIMATOR_HF;

typedef struct _AOP_POWER_SETTING
{
    ULONG DeviceId;
    ULONG Cookie;
    ULONG Unknown0;
    UCHAR Zero0[8];
    ULONG TargetState;
    ULONG Unknown1;
    UCHAR Zero1[20];
} AOP_POWER_SETTING;
#pragma pack(pop)

