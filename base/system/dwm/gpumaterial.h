/* GPU counterpart of DwmBlitWindow's transient brush-color replacement.
 * GDI BGRX alpha is undefined unless the window explicitly requests it. */
static const char *const DwmGpuMaterialSource =
    "uniform sampler2D uWindow, uBackdrop, uButtons;\n"
    "uniform vec2 uSize, uScreenSize, uCaptureOrigin, uCaptureSize, uClientMin, uClientMax;\n"
    "uniform vec4 uFrameKey, uFrameClient, uFrameButtons;\n"
    "uniform vec3 uBrush, uColorization, uKey;\n"
    "uniform float uOpacity, uAlpha, uRadius, uSaturation, uReflection;\n"
    "uniform int uGlass, uWhole, uPixelAlpha, uPremultiplied, uUseKey;\n"
    "varying vec2 vTexCoord;\n"
    "float distanceRGB(vec3 a, vec3 b) {\n"
    "    vec3 d = abs(a-b); return max(d.r,max(d.g,d.b));\n"
    "}\n"
    "float materialBump(float t, float center, float halfWidth, float peak) {\n"
    "    float q = clamp(1.0-abs((t-center)/halfWidth),0.0,1.0);\n"
    "    return peak*q*q*(3.0-2.0*q);\n"
    "}\n"
    "float materialReflection(vec2 screen) {\n"
    "    float t = (screen.x+screen.y*1.2)/(uScreenSize.x+uScreenSize.y*1.2+2.0);\n"
    "    return min(1.0,materialBump(t,0.30,0.14,1.0)+\n"
    "        materialBump(t,0.60,0.05,0.55)+materialBump(t,0.80,0.11,0.40));\n"
    "}\n"
    "vec3 materialColor(vec3 c) {\n"
    "    float a = distanceRGB(c,uBrush);\n"
    "    float b = distanceRGB(c,uColorization);\n"
    "    vec3 key = b < a ? uColorization : uBrush;\n"
    "    vec3 d = abs(c-key);\n"
    "    vec3 e = mix(key,vec3(1.0)-key,step(key,c));\n"
    "    vec3 w = clamp((e-d)/max(e-vec3(48.0/255.0),vec3(1.0/255.0)),0.0,1.0);\n"
    "    w = mix(w,vec3(1.0),step(d,vec3(48.0/255.0)));\n"
    "    float weight = min(w.r,min(w.g,w.b));\n"
    "    vec3 base = texture2D(uBackdrop,\n"
    "        (gl_FragCoord.xy-uCaptureOrigin)/uCaptureSize).rgb;\n"
    "    float luma = dot(base,vec3(77.0,151.0,28.0)/256.0);\n"
    "    base = clamp(vec3(luma)+(base-vec3(luma))*uSaturation,0.0,1.0);\n"
    "    float shine = materialReflection(\n"
    "        vec2(gl_FragCoord.x,uScreenSize.y-gl_FragCoord.y));\n"
    "    return clamp(c+(base-key)*(1.0-uOpacity)*weight+\n"
    "        vec3(uReflection*shine*weight),0.0,1.0);\n"
    "}\n"
    "void main() {\n"
    "    vec4 s = texture2D(uWindow, vTexCoord);\n"
    "    if (uUseKey != 0 && distanceRGB(s.rgb,uKey) < 0.5/255.0) discard;\n"
    "    vec2 p = vTexCoord*uSize;\n"
    "    float coverage = 1.0;\n"
    "#ifndef DWM_MATERIAL_INTERIOR\n"
    "    if (uRadius > 0.0) {\n"
    "        vec2 q = abs(p-uSize*0.5) - (uSize*0.5-vec2(uRadius));\n"
    "        float d = length(max(q,vec2(0.0))) + min(max(q.x,q.y),0.0)-uRadius;\n"
    "        coverage = clamp(0.5-d,0.0,1.0);\n"
    "        bool left = p.x < uSize.x*0.5;\n"
    "        float width = min(left ? uFrameClient.x : uSize.x-uFrameClient.z,uRadius);\n"
    "        if (q.x > 0.0 && q.y > 0.0 && width > 0.0 && -d < width+0.5) {\n"
    "            float row = p.y < uSize.y*0.5 ? uRadius+0.5 : uSize.y-uRadius-0.5;\n"
    "            vec3 fill = texture2D(uWindow,vec2(left ? width-0.5 : uSize.x-width+0.5,row)/uSize).rgb;\n"
    "            float lines = 0.0;\n"
    "            for (int k = 0; k < 64; ++k) {\n"
    "                if (float(k) >= width) break;\n"
    "                vec3 t = texture2D(uWindow,vec2(left ? float(k)+0.5 : uSize.x-float(k)-0.5,row)/uSize).rgb;\n"
    "                if (distanceRGB(t,fill) > 0.5/255.0) lines = float(k)+1.0;\n"
    "            }\n"
    "            if (lines > 0.0 && -d < lines+0.5) {\n"
    "                float u = max(-d-0.5,0.0);\n"
    "                float i = floor(u);\n"
    "                vec4 outer = texture2D(uWindow,vec2(left ? i+0.5 : uSize.x-i-0.5,row)/uSize);\n"
    "                vec4 inner = i+1.0 < lines ?\n"
    "                    texture2D(uWindow,vec2(left ? i+1.5 : uSize.x-i-1.5,row)/uSize) : s;\n"
    "                s = mix(outer,inner,u-i);\n"
    "            }\n"
    "        }\n"
    "    }\n"
    "#endif\n"
    "    if (uFrameKey.a != 0.0 && p.x >= uFrameClient.x && p.y >= uFrameClient.y &&\n"
    "        p.x < uFrameClient.z && p.y < uFrameClient.w &&\n"
    "        (p.x < uClientMin.x || p.y < uClientMin.y || p.x >= uClientMax.x || p.y >= uClientMax.y)) {\n"
    "        vec3 f = uFrameKey.rgb;\n"
    "        bool content = s.a < 0.5/255.0 && max(s.r,max(s.g,s.b)) >= 0.5/255.0;\n"
    "        if (p.x >= uFrameButtons.x && p.y >= uFrameButtons.y &&\n"
    "            p.x < uFrameButtons.z && p.y < uFrameButtons.w) {\n"
    "            f = texture2D(uButtons,(p-uFrameButtons.xy)/(uFrameButtons.zw-uFrameButtons.xy)).rgb;\n"
    "            content = false;\n"
    "        }\n"
    "        vec3 o;\n"
    "        if (content) {\n"
    "            o = uGlass != 0 ? materialColor(s.rgb) : s.rgb;\n"
    "        } else {\n"
    "            if (uGlass != 0) f = materialColor(f);\n"
    "            o = clamp(s.rgb+f*(1.0-s.a),0.0,1.0);\n"
    "        }\n"
    "        float frameAlpha = uAlpha*coverage;\n"
    "        gl_FragColor = vec4(uPremultiplied != 0 ? o*frameAlpha : o,frameAlpha);\n"
    "        return;\n"
    "    }\n"
    "    if (uGlass != 0 && (uWhole != 0 || p.x < uClientMin.x ||\n"
    "        p.y < uClientMin.y || p.x >= uClientMax.x || p.y >= uClientMax.y)) {\n"
    "        s.rgb = materialColor(s.rgb);\n"
    "    }\n"
    "    float outputAlpha = uAlpha*coverage*(uPixelAlpha != 0 ? s.a : 1.0);\n"
    "    gl_FragColor = vec4(uPremultiplied != 0 ? s.rgb*uAlpha*coverage : s.rgb,outputAlpha);\n"
    "}\n";
