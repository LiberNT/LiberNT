MACRO(DEFINE_VTBL_WRAPPER, off)
PUBLIC _vtbl_wrapper_&off
_vtbl_wrapper_&off:
    pop eax
    pop ecx
    push eax
    mov eax, [ecx]
    jmp dword ptr [eax + off]
ENDM

MACRO(DEFINE_THISCALL_WRAPPER, func, args)
EXTERN _&func&@&args:PROC
PUBLIC ___thiscall_&func
___thiscall_&func:
    pop eax
    push ecx
    push eax
    jmp _&func&@&args
ENDM

